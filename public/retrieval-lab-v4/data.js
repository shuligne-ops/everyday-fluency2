// Strict V4 evaluation: both the target construction and the complete communicative meaning are required.
setTimeout(function(){
  window.evaluate=function(m,item,raw){
    const t=norm(raw);
    const target=targetOK(m.target,t);
    const hits=cueHits(t,item[3]);
    const meaning=hits===item[3].length;
    if(item[4]==='positive-obligation' && /\b(must|have to)\b/.test(t) && !/\b(don't|do not|needn't|don't need to|do not need to)\b/.test(t)){
      return {kind:'repair',reason:'meaning',title:'Смысл получился противоположным',body:'Здесь нужно сказать «не обязательно», а не «обязательно». Повтори фразу.'};
    }
    if(target && meaning){
      return {kind:'accept',title:'Принято',body:'Смысл передан полностью и нужная конструкция использована.',independent:s.attempt===0};
    }
    if(target && !meaning){
      return {kind:'repair',reason:'meaning',title:'Конструкция есть, но фраза неполная',body:'Нужная конструкция использована, но в ответе не хватает важной части смысла. Скажи всю нужную мысль целиком.'};
    }
    if(!target && meaning){
      return {kind:'repair',reason:'target',title:'Смысл передан, но нужна эта конструкция',body:'Мысль понятна, но сейчас тренируем другой языковой способ. Попробуй выразить тот же смысл через нужную конструкцию.'};
    }
    return {kind:'repair',reason:'both',title:'Попробуем ещё раз',body:'Нужно и передать нужный смысл целиком, и использовать тренируемую конструкцию.'};
  };

  window.feedback=function(item){
    const e=s.feedback;
    const cls=e.kind==='repair'?'repair':e.kind==='note'?'note':'accept';
    let help='';
    if(e.reason==='meaning') help='Конструкция подходит. Теперь скажи нужную мысль полностью — не опускай ключевую часть ситуации.';
    else if(e.reason==='target') help='Смысл оставь тем же, но перестрой фразу через нужную конструкцию.';
    else help='Скажи нужную мысль полностью и используй тренируемую конструкцию.';
    let html='<div class="panel feedback '+cls+'" style="margin-top:16px"><h3>'+e.title+'</h3><p>'+e.body+'</p>';
    if(e.independent) html+='<div class="small" style="margin-top:8px">Самостоятельно, без подсказки.</div>';
    html+='</div>';
    if(e.kind==='repair'){
      html+='<div class="hint"><b>Попробуй ещё раз</b><div style="margin-top:6px">'+(s.attempt===0?help:'Используй: <code>'+s.module.form+'</code>')+'</div></div>';
      html+='<div class="actions"><button id="retry" class="btn primary">Попробовать ещё раз →</button>';
      if(s.attempt>=1) html+='<button id="show" class="btn ghost">Показать варианты</button>';
      html+='</div>';
    } else {
      html+='<div class="panel models" style="margin-top:14px"><b>Рекомендуемые варианты</b>';
      html+=item[2].map(function(x){return '<div class="example">• '+esc(x)+'</div>';}).join('');
      html+='</div><div class="actions"><button id="next" class="btn primary">'+(s.index===5?'Показать итог':'Дальше →')+'</button></div>';
    }
    return html;
  };
},0);
